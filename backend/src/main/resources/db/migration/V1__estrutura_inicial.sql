-- Migração V1: Estrutura inicial do Radar de Vagas (Etapa 1)

CREATE TABLE empresa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    nome_normalizado VARCHAR(255) NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_empresa_nome_normalizado UNIQUE (nome_normalizado)
);

CREATE TABLE oportunidade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT REFERENCES empresa(id),
    nome_empresa VARCHAR(255),
    cargo VARCHAR(300) NOT NULL,
    descricao TEXT NOT NULL,
    area VARCHAR(50) NOT NULL,
    senioridade VARCHAR(50) NOT NULL,
    tipo_oportunidade VARCHAR(50) NOT NULL,
    regime_contratacao VARCHAR(50) NOT NULL,
    modalidade VARCHAR(50) NOT NULL,
    localizacao VARCHAR(255),
    elegivel_brasil BOOLEAN NOT NULL DEFAULT TRUE,
    tecnologias VARCHAR(1000),
    disponibilidade_consolidada VARCHAR(50) NOT NULL,
    motivo_disponibilidade VARCHAR(500),
    link_candidatura VARCHAR(1000),
    link_origem_principal VARCHAR(1000) NOT NULL,
    fonte_principal VARCHAR(100) NOT NULL,
    mural_principal VARCHAR(200) NOT NULL,
    identificador_externo_principal VARCHAR(200) NOT NULL,
    publicado_em TIMESTAMP WITH TIME ZONE,
    primeira_observacao_em TIMESTAMP WITH TIME ZONE NOT NULL,
    ultima_observacao_em TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizado_na_fonte_em TIMESTAMP WITH TIME ZONE,
    chave_deduplicacao VARCHAR(500) NOT NULL,
    CONSTRAINT uk_oportunidade_chave_dedup UNIQUE (chave_deduplicacao)
);

CREATE INDEX idx_oportunidade_publicado_em ON oportunidade(publicado_em DESC);
CREATE INDEX idx_oportunidade_primeira_obs ON oportunidade(primeira_observacao_em DESC);
CREATE INDEX idx_oportunidade_tipo_disp ON oportunidade(tipo_oportunidade, disponibilidade_consolidada);

CREATE TABLE anuncio_origem (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    oportunidade_id BIGINT NOT NULL REFERENCES oportunidade(id) ON DELETE CASCADE,
    fornecedor VARCHAR(100) NOT NULL,
    identificador_mural VARCHAR(200) NOT NULL,
    identificador_externo VARCHAR(200) NOT NULL,
    titulo_original VARCHAR(500) NOT NULL,
    corpo_original TEXT NOT NULL,
    labels_originais VARCHAR(1000),
    url_origem VARCHAR(1000) NOT NULL,
    url_candidatura VARCHAR(1000),
    disponibilidade_observada VARCHAR(50) NOT NULL,
    motivo_indisponibilidade VARCHAR(500),
    publicado_na_fonte_em TIMESTAMP WITH TIME ZONE,
    atualizado_na_fonte_em TIMESTAMP WITH TIME ZONE,
    primeira_observacao_em TIMESTAMP WITH TIME ZONE NOT NULL,
    ultima_observacao_em TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_anuncio_origem_identidade UNIQUE (fornecedor, identificador_mural, identificador_externo)
);

CREATE INDEX idx_anuncio_oportunidade ON anuncio_origem(oportunidade_id);

CREATE TABLE configuracao_fonte (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fornecedor VARCHAR(100) NOT NULL,
    identificador_mural VARCHAR(200) NOT NULL,
    nome_exibicao VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    cadencia_minutos INTEGER NOT NULL DEFAULT 360,
    ultima_coleta_sucesso_em TIMESTAMP WITH TIME ZONE,
    cursor_ultima_atualizacao TIMESTAMP WITH TIME ZONE,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_configuracao_fonte UNIQUE (fornecedor, identificador_mural)
);

CREATE TABLE execucao_coleta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fornecedor VARCHAR(100) NOT NULL,
    identificador_mural VARCHAR(200) NOT NULL,
    status VARCHAR(50) NOT NULL,
    iniciado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    finalizado_em TIMESTAMP WITH TIME ZONE,
    anuncios_recebidos INTEGER NOT NULL DEFAULT 0,
    anuncios_validos INTEGER NOT NULL DEFAULT 0,
    anuncios_novos INTEGER NOT NULL DEFAULT 0,
    anuncios_atualizados INTEGER NOT NULL DEFAULT 0,
    anuncios_repetidos INTEGER NOT NULL DEFAULT 0,
    anuncios_ignorados INTEGER NOT NULL DEFAULT 0,
    erros_contagem INTEGER NOT NULL DEFAULT 0,
    rate_limit_restante INTEGER,
    rate_limit_reset_em TIMESTAMP WITH TIME ZONE,
    erro_resumido VARCHAR(1000)
);

CREATE INDEX idx_execucao_coleta_iniciado ON execucao_coleta(iniciado_em DESC);
CREATE INDEX idx_execucao_coleta_fonte_status ON execucao_coleta(fornecedor, identificador_mural, status);

CREATE TABLE acao_pessoal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    oportunidade_id BIGINT NOT NULL REFERENCES oportunidade(id) ON DELETE CASCADE,
    ja_me_candidatei BOOLEAN NOT NULL DEFAULT FALSE,
    oculta BOOLEAN NOT NULL DEFAULT FALSE,
    candidatado_em TIMESTAMP WITH TIME ZONE,
    ocultado_em TIMESTAMP WITH TIME ZONE,
    atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_acao_pessoal_oportunidade UNIQUE (oportunidade_id)
);
